window.runMarkdownEditBrowserChecks = async () => {
  const checks = [], check = (name, value) => { if (!value) throw Error(name); checks.push(name); };
  const settle = () => new Promise(resolve => setTimeout(resolve, 220));
  const chat = document.createElement('section'); chat.id = 'chat'; chat.className = 'chat';
  chat.style.cssText = 'display:flex;flex-direction:column;width:100vw;height:100dvh';
  chat.innerHTML = '<header class="chat-head"></header><div class="timeline" tabindex="0"></div><div class="composer"><textarea></textarea></div>';
  document.body.append(chat);
  let disk = '# 文档\n\n正文 alpha alpha\n', revision = 1, writes = 0, reads = 0, lost = false, rejectWrite = false, release;
  const version = () => String(revision).padStart(64,'0');
  const wb = new Workbench({chat, notify:() => {}, request:async (url, body) => {
    if (body) {
      writes++;
      if (release) await release.promise;
      if (rejectWrite) throw Error('offline');
      if (body.version !== version()) return {outcome:'conflict'};
      disk = body.text; revision++;
      if (lost) throw Error('receipt lost');
      return {outcome:'saved',version:version(),size:new TextEncoder().encode(disk).length};
    }
    reads++; return {kind:'text',name:'说明.md',text:disk,version:version(),size:disk.length};
  }});
  wb.refreshSideChats = () => {};
  wb.open('11111111-1111-4111-8111-111111111111','remote-ssh:fixture');
  await wb.preview(wb.current,{path:'docs/说明.md',name:'说明.md'});
  const tab = wb.current.files[0], editor = tab.editor;
  if (!editor) throw Error(tab.body.textContent);
  const type = text => { editor.input.dispatchEvent(new InputEvent('beforeinput')); editor.input.value = text; editor.input.dispatchEvent(new InputEvent('input')); };
  check('Markdown starts in preview with an edit control', editor.mode === 'preview' && editor.editor.hidden && !editor.content.hidden);
  editor.modeButtons.get('edit').click();
  check('edit mode shows a named textarea with the original source', !editor.editor.hidden && editor.content.hidden && editor.input.value === disk && editor.input.getAttribute('aria-label'));
  let copied;
  Object.defineProperty(navigator,'clipboard',{value:{writeText:async text=>{copied=text;}},configurable:true});
  await editor.copyButton.onclick();
  check('copy uses the shared clipboard workflow and exact Markdown source', copied === disk);
  editor.input.setSelectionRange(2,4); editor.prefix('## ');
  check('changing heading level replaces the existing heading marker', editor.input.value.startsWith('## 文档'));
  editor.undo();
  editor.input.setSelectionRange(2,4); editor.toolbar.querySelector('[data-i18n-title="粗体"]').click();
  check('bold wraps the selected Chinese text', editor.input.value.startsWith('# **文档**'));
  editor.undoButton.click(); check('undo restores the original document', editor.input.value === disk);
  editor.redoButton.click(); check('redo restores formatting', editor.input.value.includes('**文档**'));
  editor.input.setSelectionRange(4,6); editor.wrap('**','**','文字');
  check('repeating bold removes the surrounding markers', editor.input.value === disk);
  editor.input.setSelectionRange(6,6); editor.prefix('- [ ] ');
  check('task list prefixes the current line', editor.input.value.includes('- [ ] 正文'));
  editor.undo(); editor.find(); editor.query.value = 'alpha'; editor.query.oninput(); editor.replacement.value = '$&中文'; editor.replace(true);
  check('replace all treats replacement text literally', editor.input.value.includes('$&中文 $&中文') && !editor.input.value.includes('alpha'));
  editor.undo(); check('replace all is one undo step', editor.input.value === disk);
  editor.input.setSelectionRange(0,editor.input.value.length); const unindented = editor.input.value;
  editor.indent(false); check('indent keeps the selected text on every line', editor.input.value === unindented.slice(0,-1).split('\n').map(line=>'  '+line).join('\n')+'\n');
  editor.indent(true); check('outdent restores all selected lines', editor.input.value === unindented);
  for (const [left,right] of [['*','*'],['~~','~~'],['`','`'],['\n```\n','\n```\n'],['[','](https://)'],['![','](https://)']]) {
    editor.input.setSelectionRange(2,4); editor.wrap(left,right,'文字');
    check('format insertion '+left, editor.input.value.includes(left+'文档'+right)); editor.undo();
  }
  editor.query.value = ''; const before = editor.input.value; editor.replace(true);
  check('empty search cannot alter the document', editor.input.value === before);
  editor.findbar.hidden = true;
  type('# 修改后的文档\n\n**加粗内容**\n'); editor.show('split'); await settle();
  check('live preview renders the unsaved draft', tab.markdown.textContent.includes('加粗内容') && tab.markdown.querySelector('strong'));
  check('live preview replaces previous content instead of accumulating copies', tab.markdown.querySelectorAll('.markdown-body').length === 1 && !tab.markdown.textContent.includes('alpha'));
  check('draft is marked on its tab', wb.tabs.querySelector('.wb-tab-dirty'));
  const input = editor.input, position = input.selectionStart;
  wb.select('chat'); wb.select(tab.id);
  check('switching tabs preserves the draft and cursor', tab.editor === editor && editor.input === input && editor.dirty && input.selectionStart === position);
  await editor.save(); check('save writes source and clears dirty state', writes === 1 && !editor.dirty && disk === input.value && editor.saveButton.disabled);
  await editor.save(); check('saving an unchanged document never writes', writes === 1);
  type('草稿与电脑冲突'); disk = '# 电脑的新内容'; revision++;
  await editor.save(); check('conflicting save preserves both draft and disk', editor.conflict && input.value === '草稿与电脑冲突' && disk === '# 电脑的新内容' && editor.saveButton.disabled);
  let closing = wb.close(tab.id); await Promise.resolve();
  check('closing a dirty document asks about the draft', !!editor.leaveDialog?.open);
  editor.leaveDialog.querySelector('button').click(); await closing;
  check('cancel close keeps the tab and text', wb.current.files.includes(tab) && input.value === '草稿与电脑冲突');
  let refreshing = wb.refreshPreview(wb.current,tab); await Promise.resolve();
  editor.leaveDialog.querySelectorAll('button')[1].click(); await refreshing;
  check('explicit discard and refresh loads the current disk version', tab.editor !== editor && tab.editor.input.value === disk && editor.disposed);
  const next = tab.editor;
  const typeNext = text => { next.input.dispatchEvent(new InputEvent('beforeinput')); next.input.value = text; next.input.dispatchEvent(new InputEvent('input')); };
  next.show('edit'); typeNext('保存成功但回执丢失'); lost = true; await next.save();
  const lostWrites = writes; await next.save();
  check('unknown write is not automatically replayed', next.needsCheck && writes === lostWrites && next.input.value === disk);
  typeNext('保存期间继续修改'); await next.checkSave();
  check('read-only verification confirms a lost receipt without losing newer edits', !next.needsCheck && next.dirty && next.original === disk && next.input.value === '保存期间继续修改' && writes === lostWrites);
  lost = false; rejectWrite = true; await next.save(); rejectWrite = false; await next.checkSave();
  check('a failed write keeps the draft and permits an explicit retry after checking', !next.needsCheck && next.dirty && !next.saveButton.disabled);
  let done; release = {promise:new Promise(resolve => {done = resolve;})}; const saving = next.save();
  const count = writes; await next.save();
  check('double save issues only one request', next.saving && writes === count);
  await wb.close(tab.id); check('close is blocked while save is pending', wb.current.files.includes(tab));
  typeNext('保存期间新输入'); done(); await saving; release = null;
  check('late save completion does not clear newer edits', next.dirty && next.input.value === '保存期间新输入' && next.original === disk);
  next.show('split'); await settle();
  check('updated preview contains only the latest draft', tab.markdown.querySelectorAll('.markdown-body').length === 1 && tab.markdown.textContent === '保存期间新输入');
  wb.openPreviewFullscreen(wb.current,tab,tab.previewContent,tab.fullscreenButton);
  check('fullscreen retains the live editor and its draft', wb.previewFullscreen?.tab === tab && next.input.isConnected && next.dirty);
  wb.closePreviewFullscreen();
  const bounds = next.input.getBoundingClientRect(), preview = tab.markdown.getBoundingClientRect();
  check('editing and preview stay inside the viewport', bounds.width > 0 && bounds.right <= innerWidth+1 && preview.width > 0 && preview.right <= innerWidth+1 && bounds.height > 40 && preview.height > 20);
  check('narrow split stacks editor above preview', innerWidth > 640 || preview.top >= bounds.bottom);
  check('toolbar buttons have accessible names', [...next.toolbar.querySelectorAll('button')].every(button => button.getAttribute('aria-label')));
  check('file requests remain bound to the SSH session', wb.url(wb.current,'save',tab.entry.path).includes('host=remote-ssh%3Afixture'));
  const key = wb.current.key;
  wb.open('22222222-2222-4222-8222-222222222222','local'); await wb.preview(wb.current,{path:'docs/说明.md',name:'说明.md'});
  const other = wb.current.files[0].editor; other.show('edit');
  other.input.dispatchEvent(new InputEvent('beforeinput')); other.input.value = '另一个会话的草稿'; other.input.dispatchEvent(new InputEvent('input'));
  next.original = next.input.value; next.update();
  check('a hidden session cannot clear another sessions dirty indicator', wb.tabs.querySelector('.wb-tab-dirty'));
  wb.open('11111111-1111-4111-8111-111111111111','remote-ssh:fixture');
  check('returning to a session restores the same editor', wb.current.key === key && tab.editor === next && next.input.value === '保存期间新输入');
  typeNext('超过限制'.repeat(150000)); const beforeOversize = writes;
  await next.save(); check('oversize drafts are kept without issuing a write', writes === beforeOversize && next.dirty && !next.needsCheck);
  typeNext('最后一份草稿'); const confirming = next.confirmLeave(); await Promise.resolve();
  next.leaveDialog.querySelectorAll('button')[2].click();
  check('save and continue waits for confirmed saving', await confirming && !next.dirty && disk === '最后一份草稿');
  window.markdownFixture = {wb,tab,editor:next,chat,checks,reads,writes};
  return {passed:checks.length,checks};
};
