// Isolated reference fixture only: skills, nested files and sectioned sessions.
async function runReferencePickerBrowserTests(){
  const checks=[],check=(value,label)=>{if(!value)throw Error(label);checks.push(label);};
  const waitFor=async test=>{for(let i=0;i<100;i++){if(test())return;await new Promise(resolve=>setTimeout(resolve,25));}throw Error('Reference fixture timed out');};
  const picker=composerReferences,all=selector=>[...picker.list.querySelectorAll(selector)];
  const row=id=>all('.reference-item').find(node=>node.dataset.referenceId===id);
  const chat=currentId,host=currentHost,draft='Review these references';
  $('message').value=draft;$('message').setSelectionRange(draft.length,draft.length);
  check($('skills-button').textContent.trim()==='＋','The composer offers a plus reference button');
  check(!$('skill-pills')&&!$('skill-count'),'The old selected-skill UI is removed');
  await picker.open();
  check(picker.tabButtons.size===3,'The picker offers skills, project files and sessions');
  picker.search.value='code-review';picker.search.dispatchEvent(new Event('input',{bubbles:true}));
  await waitFor(()=>!!row('review-skill'));row('review-skill').click();
  await waitFor(()=>!picker.dialog.open);
  check($('message').value.includes('$code-review'),'A skill inserts its dollar-prefixed name into the draft');
  await picker.open();await picker.setTab('files');
  const folder=path=>picker.list.querySelector('details[data-reference-group="directory:'+path+'"]');
  check(!!folder('src')&&!row('directory:src/deep/index.js'),'The file picker starts with a lazy directory tree');
  folder('src').querySelector('summary').click();await waitFor(()=>!!folder('src/deep'));
  folder('src/deep').querySelector('summary').click();await waitFor(()=>!!row('directory:src/deep/index.js'));
  check(folder('src').contains(folder('src/deep'))&&folder('src/deep').contains(row('directory:src/deep/index.js')),'Nested folders retain their full directory hierarchy');
  row('directory:src/deep/index.js').click();await waitFor(()=>!picker.dialog.open);
  check($('message').value.includes('D:\\fixture\\project\\src\\deep\\index.js'),'A file inserts the full native Windows path');
  await picker.open();await picker.setTab('files');
  picker.search.value='needle';picker.search.dispatchEvent(new Event('input',{bubbles:true}));
  await waitFor(()=>!!row('directory:src/deep/needle.txt'));
  check(folder('src').contains(folder('src/deep'))&&folder('src/deep').contains(row('directory:src/deep/needle.txt')),'Project-wide search retains the matching file ancestor folders');
  check(all('.reference-item').length===1,'File search filters unrelated leaves');
  picker.search.value='';picker.search.dispatchEvent(new Event('input',{bubbles:true}));await waitFor(()=>picker.active.query===''&&!picker.loading&&!!folder('src'));
  picker.hiddenFiles.checked=true;picker.hiddenFiles.dispatchEvent(new Event('change',{bubbles:true}));
  await waitFor(()=>!!row('directory:.hidden.txt'));check(!!row('directory:.hidden.txt'),'Hidden project files can be included explicitly');
  await picker.setTab('sessions');
  const section=picker.list.querySelector('details[data-reference-group="section:planning"]');
  const project=picker.list.querySelector('details[data-reference-group="project:local|fixture"]');
  check(!!section&&!!project&&section.contains(project),'Session references retain section and project structure');
  check(!!picker.list.querySelector('details[data-reference-group="pinned"]'),'Pinned sessions retain their own section');
  picker.search.value='Needle chat';picker.search.dispatchEvent(new Event('input',{bubbles:true}));
  await waitFor(()=>!!row('local|22222222-2222-4222-8222-222222222222')&&all('.reference-item').length===1);
  check(!!picker.list.querySelector('details[data-reference-group="section:planning"] details[data-reference-group="project:local|fixture"]'),'Session search retains the matching section and project');
  row('local|22222222-2222-4222-8222-222222222222').click();await waitFor(()=>!picker.dialog.open);
  check($('message').value.includes('codex://threads/22222222-2222-4222-8222-222222222222'),'A session inserts the same native link as Copy session path');
  check(currentId===chat&&currentHost===host,'Choosing a session reference does not open or switch that session');
  check($('message').value.startsWith(draft),'All reference insertions retain the original message draft');
  await picker.open();await picker.setTab('sessions');
  const rect=picker.dialog.getBoundingClientRect();
  check(rect.left>=0&&rect.right<=innerWidth&&rect.top>=0&&rect.bottom<=innerHeight,'The picker fits inside the available viewport');
  check(picker.dialog.scrollHeight<=picker.dialog.clientHeight+1,'Only the reference list scrolls inside the modal');
  picker.close();
  const text=$('message').value;await $('composer').onsubmit({preventDefault(){}});
  check($('message').value==='','The draft clears only after successful sending');
  return {checks,text};
}
